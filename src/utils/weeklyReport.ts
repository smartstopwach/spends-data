import { ALL_CATEGORY_MAP } from '../constants';
import { Transaction } from '../types';
import { formatINR, getTodayISO, shiftISODate } from './mathAndFormat';

export interface WeeklyReport {
  fromISO: string;
  toISO: string;
  periodLabel: string;
  days: number;
  income: number;
  spend: number;
  net: number;
  incomeCount: number;
  spendCount: number;
  dailyAvg: number;
  topCategory: string | null;
  topCategoryAmount: number;
  categories: Array<{ label: string; amount: number; percentage: number; count: number }>;
  dailyRows: Array<{ date: string; label: string; spend: number; income: number; count: number }>;
  biggestSpend: Transaction | null;
  walletBalance: number;
  subject: string;
  text: string;
  html: string;
}

const shortDate = (iso: string): string => {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
};

const longDay = (iso: string): string => {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString('en-IN', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
  });
};

/**
 * Builds the weekly digest for the last 7 days ending today (inclusive).
 */
export function buildWeeklyReport(
  transactions: Transaction[],
  todayISO: string = getTodayISO()
): WeeklyReport {
  const fromISO = shiftISODate(todayISO, -6);
  const windowTx = transactions
    .filter((tx) => tx.date >= fromISO && tx.date <= todayISO)
    .sort((a, b) => a.date.localeCompare(b.date) || a.createdAt - b.createdAt);

  let income = 0;
  let spend = 0;
  let incomeCount = 0;
  let spendCount = 0;
  const catTotals = new Map<string, { amount: number; count: number }>();
  const dailyMap = new Map<string, { spend: number; income: number; count: number }>();
  let biggestSpend: Transaction | null = null;

  for (const tx of windowTx) {
    const day = dailyMap.get(tx.date) ?? { spend: 0, income: 0, count: 0 };
    day.count += 1;

    if (tx.type === 'income') {
      income += tx.amount;
      incomeCount += 1;
      day.income += tx.amount;
    } else {
      spend += tx.amount;
      spendCount += 1;
      day.spend += tx.amount;
      const prev = catTotals.get(tx.category) ?? { amount: 0, count: 0 };
      catTotals.set(tx.category, { amount: prev.amount + tx.amount, count: prev.count + 1 });
      if (!biggestSpend || tx.amount > biggestSpend.amount) biggestSpend = tx;
    }
    dailyMap.set(tx.date, day);
  }

  const categories = [...catTotals.entries()]
    .map(([category, stat]) => ({
      label: ALL_CATEGORY_MAP[category]?.label ?? category,
      amount: Math.round(stat.amount * 100) / 100,
      percentage: spend > 0 ? Math.round((stat.amount / spend) * 1000) / 10 : 0,
      count: stat.count,
    }))
    .sort((a, b) => b.amount - a.amount);

  const dailyRows: WeeklyReport['dailyRows'] = [];
  for (let i = 0; i < 7; i += 1) {
    const iso = shiftISODate(fromISO, i);
    const day = dailyMap.get(iso);
    dailyRows.push({
      date: iso,
      label: longDay(iso),
      spend: Math.round((day?.spend ?? 0) * 100) / 100,
      income: Math.round((day?.income ?? 0) * 100) / 100,
      count: day?.count ?? 0,
    });
  }

  const walletBalance =
    Math.round(
      transactions.reduce((sum, tx) => sum + (tx.type === 'income' ? tx.amount : -tx.amount), 0) *
        100
    ) / 100;

  const periodLabel = `${shortDate(fromISO)} – ${shortDate(todayISO)}`;
  const subject = `GharKaHisaab — weekly spends ${formatINR(spend)} (${periodLabel})`;
  const top = categories[0] ?? null;

  const text = [
    `GharKaHisaab · Weekly Report`,
    periodLabel,
    '',
    `Money in:  ${formatINR(income)} (${incomeCount} credits)`,
    `Spends:    ${formatINR(spend)} (${spendCount} debits)`,
    `Net:       ${income - spend >= 0 ? '+' : '−'}${formatINR(Math.abs(income - spend))}`,
    `Daily avg: ${formatINR(spend > 0 ? Math.round(spend / 7) : 0)}`,
    `Balance:   ${formatINR(walletBalance)}`,
    '',
    'Category breakdown:',
    ...(categories.length
      ? categories.map((c) => `  • ${c.label}: ${formatINR(c.amount)} (${c.percentage}%)`)
      : ['  • No spends recorded this week']),
    '',
    'Day by day:',
    ...dailyRows.map(
      (d) => `  ${d.label}: spend ${formatINR(d.spend)} | in ${formatINR(d.income)}`
    ),
    '',
    '— Generated by GharKaHisaab',
  ].join('\n');

  const catRows = categories.length
    ? categories
        .map(
          (c) => `
      <tr>
        <td style="padding:6px 0;font-size:13px;color:#334155">${c.label}</td>
        <td style="padding:6px 0;font-size:13px;color:#0f172a;font-weight:700;text-align:right">${formatINR(
          c.amount
        )}</td>
        <td style="padding:6px 0 6px 12px;font-size:12px;color:#94a3b8;text-align:right;width:52px">${
          c.percentage
        }%</td>
      </tr>`
        )
        .join('')
    : '<tr><td colspan="3" style="padding:6px 0;font-size:13px;color:#94a3b8">No spends this week 🎉</td></tr>';

  const dayRows = dailyRows
    .map(
      (d) => `
      <tr>
        <td style="padding:5px 0;font-size:12px;color:#64748b">${d.label}</td>
        <td style="padding:5px 0;font-size:12px;color:#0f172a;font-weight:600;text-align:right">${
          d.spend > 0 ? `−${formatINR(d.spend)}` : '—'
        }</td>
        <td style="padding:5px 0 5px 12px;font-size:12px;color:#059669;font-weight:600;text-align:right">${
          d.income > 0 ? `+${formatINR(d.income)}` : ''
        }</td>
      </tr>`
    )
    .join('');

  const html = `
  <div style="font-family:Inter,-apple-system,Segoe UI,Roboto,sans-serif;background:#f6f7f9;padding:24px">
    <div style="max-width:560px;margin:0 auto;background:#fff;border:1px solid #e5e8ee;border-radius:16px;overflow:hidden">
      <div style="background:linear-gradient(135deg,#1e1b4b,#4338ca);padding:22px 24px;color:#fff">
        <p style="margin:0;font-size:11px;letter-spacing:.14em;text-transform:uppercase;color:#c7d2fe;font-weight:700">GharKaHisaab</p>
        <h1 style="margin:6px 0 0;font-size:20px;font-weight:800">Weekly spend report</h1>
        <p style="margin:4px 0 0;font-size:12px;color:#c7d2fe">${periodLabel}</p>
      </div>
      <div style="padding:20px 24px">
        <table style="width:100%;border-collapse:collapse;margin-bottom:18px">
          <tr>
            <td style="padding:10px;background:#f8fafc;border-radius:10px;font-size:11px;color:#64748b">Money in<br><span style="font-size:15px;font-weight:800;color:#059669">${formatINR(
              income
            )}</span></td>
            <td style="width:8px"></td>
            <td style="padding:10px;background:#f8fafc;border-radius:10px;font-size:11px;color:#64748b">Spends<br><span style="font-size:15px;font-weight:800;color:#0f172a">${formatINR(
              spend
            )}</span></td>
            <td style="width:8px"></td>
            <td style="padding:10px;background:#f8fafc;border-radius:10px;font-size:11px;color:#64748b">Balance<br><span style="font-size:15px;font-weight:800;color:#4f46e5">${formatINR(
              walletBalance
            )}</span></td>
          </tr>
        </table>
        <p style="margin:0 0 6px;font-size:11px;font-weight:700;letter-spacing:.08em;text-transform:uppercase;color:#94a3b8">Where money went</p>
        <table style="width:100%;border-collapse:collapse">${catRows}</table>
        <p style="margin:18px 0 6px;font-size:11px;font-weight:700;letter-spacing:.08em;text-transform:uppercase;color:#94a3b8">Day by day</p>
        <table style="width:100%;border-collapse:collapse">${dayRows}</table>
        ${
          top
            ? `<p style="margin:18px 0 0;font-size:12px;color:#475569">Biggest category: <strong>${top.label}</strong> · ${formatINR(
                top.amount
              )}</p>`
            : ''
        }
      </div>
      <div style="padding:14px 24px;border-top:1px solid #eef2f6;font-size:11px;color:#94a3b8">
        Sent by GharKaHisaab · your data never leaves this browser unless you export or email it.
      </div>
    </div>
  </div>`;

  return {
    fromISO,
    toISO: todayISO,
    periodLabel,
    days: 7,
    income: Math.round(income * 100) / 100,
    spend: Math.round(spend * 100) / 100,
    net: Math.round((income - spend) * 100) / 100,
    incomeCount,
    spendCount,
    dailyAvg: spend > 0 ? Math.round(spend / 7) : 0,
    topCategory: top?.label ?? null,
    topCategoryAmount: top?.amount ?? 0,
    categories,
    dailyRows,
    biggestSpend,
    walletBalance,
    subject,
    text,
    html,
  };
}

export interface EmailJSDelivery {
  serviceId: string;
  templateId: string;
  publicKey: string;
}

/** Sends the digest through EmailJS (browser-only, no backend needed). */
export async function sendReportViaEmailJS(
  report: WeeklyReport,
  toEmail: string,
  creds: EmailJSDelivery
): Promise<void> {
  const res = await fetch('https://api.emailjs.com/api/v1.0/email/send', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      service_id: creds.serviceId,
      template_id: creds.templateId,
      user_id: creds.publicKey,
      template_params: {
        to_email: toEmail,
        subject: report.subject,
        period: report.periodLabel,
        money_in: formatINR(report.income),
        spends: formatINR(report.spend),
        balance: formatINR(report.walletBalance),
        daily_avg: formatINR(report.dailyAvg),
        top_category: report.topCategory ?? '—',
        message: report.html,
        message_text: report.text,
        reply_to: toEmail,
      },
    }),
  });

  if (!res.ok) {
    const detail = await res.text();
    throw new Error(`EmailJS ${res.status}: ${detail.slice(0, 160)}`);
  }
}

/** Opens Gmail compose pre-filled with the digest. */
export function openGmailCompose(report: WeeklyReport, toEmail: string): void {
  const url =
    'https://mail.google.com/mail/?view=cm&fs=1' +
    `&to=${encodeURIComponent(toEmail)}` +
    `&su=${encodeURIComponent(report.subject)}` +
    `&body=${encodeURIComponent(report.text)}`;
  if (typeof window !== 'undefined') window.open(url, '_blank', 'noopener,noreferrer');
}

/** Fallback mailto (works for any mail app / account). */
export function openMailto(report: WeeklyReport, toEmail: string): void {
  const url = `mailto:${toEmail}?subject=${encodeURIComponent(
    report.subject
  )}&body=${encodeURIComponent(report.text)}`;
  if (typeof window !== 'undefined') window.location.href = url;
}
